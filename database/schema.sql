CREATE TABLE IF NOT EXISTS bairro (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome varchar(120) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS prefeitura (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome varchar(160) NOT NULL,
    cnpj varchar(14) NOT NULL UNIQUE CHECK (cnpj ~ '^[0-9]{14}$')
);

CREATE TABLE IF NOT EXISTS pessoa (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome varchar(160) NOT NULL,
    cpf varchar(11) NOT NULL UNIQUE CHECK (cpf ~ '^[0-9]{11}$'),
    endereco varchar(240) NOT NULL
);

CREATE TABLE IF NOT EXISTS proprietario (
    id bigint PRIMARY KEY REFERENCES pessoa(id) ON DELETE CASCADE,
    telefone varchar(30) NOT NULL,
    email varchar(160) NOT NULL
);

CREATE TABLE IF NOT EXISTS gestor_horta (
    id bigint PRIMARY KEY REFERENCES pessoa(id) ON DELETE CASCADE,
    matricula varchar(40) NOT NULL,
    data_contratacao date NOT NULL,
    ajuda_custo numeric(12,2) NOT NULL CHECK (ajuda_custo >= 0),
    prefeitura_id bigint NOT NULL REFERENCES prefeitura(id),
    UNIQUE (prefeitura_id, matricula)
);

CREATE TABLE IF NOT EXISTS terreno (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    endereco varchar(240) NOT NULL,
    area numeric(12,2) NOT NULL CHECK (area > 0),
    status varchar(20) NOT NULL CHECK (status IN ('DISPONIVEL', 'INDISPONIVEL')),
    situacao_legal varchar(20) NOT NULL CHECK (situacao_legal IN ('A_ANALISAR', 'APTO', 'INAPTO')),
    bairro_id bigint NOT NULL REFERENCES bairro(id),
    prefeitura_id bigint NOT NULL REFERENCES prefeitura(id),
    proprietario_id bigint REFERENCES proprietario(id),
    UNIQUE (id, prefeitura_id, proprietario_id)
);

CREATE TABLE IF NOT EXISTS contrato (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    terreno_id bigint NOT NULL,
    prefeitura_id bigint NOT NULL,
    proprietario_id bigint NOT NULL,
    data_inicio date NOT NULL,
    data_fim date NOT NULL CHECK (data_fim >= data_inicio),
    valor_aluguel numeric(12,2) NOT NULL CHECK (valor_aluguel >= 0),
    percentual_producao numeric(5,2) NOT NULL CHECK (percentual_producao BETWEEN 0 AND 100),
    incentivo_fiscal varchar(240),
    tipo_adesao varchar(20) NOT NULL CHECK (tipo_adesao IN ('LEGAL', 'VOLUNTARIA')),
    FOREIGN KEY (terreno_id, prefeitura_id, proprietario_id)
        REFERENCES terreno(id, prefeitura_id, proprietario_id)
);

CREATE TABLE IF NOT EXISTS horta (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome varchar(160) NOT NULL,
    terreno_id bigint NOT NULL UNIQUE REFERENCES terreno(id),
    gestor_id bigint NOT NULL REFERENCES gestor_horta(id)
);

CREATE TABLE IF NOT EXISTS familia (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome varchar(160) NOT NULL,
    horta_id bigint NOT NULL REFERENCES horta(id)
);

CREATE TABLE IF NOT EXISTS membro_familia (
    id bigint PRIMARY KEY REFERENCES pessoa(id) ON DELETE CASCADE,
    familia_id bigint NOT NULL REFERENCES familia(id)
);

CREATE TABLE IF NOT EXISTS producao (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    horta_id bigint NOT NULL REFERENCES horta(id)
);

CREATE TABLE IF NOT EXISTS producao_horta (
    id bigint PRIMARY KEY REFERENCES producao(id) ON DELETE CASCADE,
    produto varchar(120) NOT NULL,
    quantidade_produzida numeric(12,2) NOT NULL CHECK (quantidade_produzida > 0),
    data_plantio date NOT NULL,
    data_colheita date NOT NULL CHECK (data_colheita >= data_plantio)
);

CREATE TABLE IF NOT EXISTS minhocario (
    id bigint PRIMARY KEY REFERENCES producao(id) ON DELETE CASCADE,
    quantidade_minhocas integer NOT NULL CHECK (quantidade_minhocas >= 0),
    quantidade_adubo numeric(12,2) NOT NULL CHECK (quantidade_adubo >= 0),
    data_registro date NOT NULL
);

CREATE TABLE IF NOT EXISTS distribuicao (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    colheita_id bigint NOT NULL REFERENCES producao_horta(id),
    familia_id bigint NOT NULL REFERENCES familia(id),
    quantidade numeric(12,2) NOT NULL CHECK (quantidade > 0),
    data_entrega date NOT NULL
);

CREATE INDEX IF NOT EXISTS terreno_bairro_idx ON terreno(bairro_id);
CREATE INDEX IF NOT EXISTS horta_gestor_idx ON horta(gestor_id);
CREATE INDEX IF NOT EXISTS producao_horta_idx ON producao(horta_id);
CREATE INDEX IF NOT EXISTS distribuicao_colheita_idx ON distribuicao(colheita_id);
CREATE INDEX IF NOT EXISTS distribuicao_familia_idx ON distribuicao(familia_id);
